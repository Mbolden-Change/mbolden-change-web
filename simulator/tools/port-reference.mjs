// Copies the calculation code out of simulator/reference/index.html into
// frontend/lib/simulator/ byte-for-byte. Only the import/export lines around
// each verbatim block are written by hand here; simulator/tests/verbatim.test.js
// checks the blocks still match the reference.
//
// Run from the repo root: node simulator/tools/port-reference.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const ref = fs.readFileSync(path.join(root, 'simulator/reference/index.html'), 'utf8').split('\n');
const lines = (a, b) => ref.slice(a - 1, b).join('\n');
const begin = (a, b) => `// ---- BEGIN VERBATIM reference lines ${a}-${b} ----`;
const end = '// ---- END VERBATIM ----';
const out = path.join(root, 'frontend/lib/simulator');

export const BLOCKS = {
  'adapter.js': [7622, 7672],
  'model.js': [7679, 9101],
};

function topLevelNames(text) {
  const names = [];
  for (const m of text.matchAll(/^ {4}(?:const|function|let) ([A-Za-z_$][\w$]*)/gm)) names.push(m[1]);
  return [...new Set(names)];
}

function write(file, header, [a, b], footer) {
  const body = [header, begin(a, b), lines(a, b), end, footer, ''].join('\n');
  fs.writeFileSync(path.join(out, file), body);
  console.log(`${file}: reference lines ${a}-${b}`);
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  write('adapter.js', `/* Generated by simulator/tools/port-reference.mjs. Do not edit the verbatim block. */
import BenefitsEngine from './engine/engine.js';
import ENGINE_PARAMS from './engine/parameters.json';
import CALEITC_TABLE_2025 from './engine/caleitc-table-2025.json';

// The reference build attaches the engine to the browser window. This module-local
// object stands in for it, so the block below runs unchanged.
const window = { ENGINE_PARAMS, CALEITC_TABLE_2025 };
`, BLOCKS['adapter.js'], `
export const ENGINE = window.ENGINE;
export const EngineAdapter = window.EngineAdapter;
export { ENGINE_PARAMS };`);

  const [a, b] = BLOCKS['model.js'];
  const names = topLevelNames(lines(a, b));
  write('model.js', `/* Generated by simulator/tools/port-reference.mjs. Do not edit the verbatim block. */
import { EngineAdapter } from './adapter.js';
`, [a, b], `
export {
  ${names.join(',\n  ')},
};`);
}
